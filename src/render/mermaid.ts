import path from 'node:path'
import type { Category, Completeness, FlowNode } from '../schema/flow.js'
import { isLabeled, type AnyFlow, type LabeledNode } from '../schema/labeled.js'
import { normalizeCode } from '../util.js'

type AnyNode = FlowNode | LabeledNode

/** Legend colors, loosely following Slack's chart: prefs blue, state yellow, input orange. */
const CLASS_DEFS: Record<Category | 'yes' | 'no' | 'outcome' | 'opaque' | 'action' | 'start', string> = {
  pref: 'fill:#dbeafe,stroke:#3b82f6,color:#1e3a8a',
  state: 'fill:#fef9c3,stroke:#ca8a04,color:#713f12',
  input: 'fill:#ffedd5,stroke:#ea580c,color:#7c2d12',
  external: 'fill:#f3f4f6,stroke:#6b7280,color:#111827',
  yes: 'fill:#22c55e,stroke:#15803d,color:#ffffff',
  no: 'fill:#ef4444,stroke:#b91c1c,color:#ffffff',
  outcome: 'fill:#e9d5ff,stroke:#7e22ce,color:#3b0764',
  opaque: 'fill:#ffffff,stroke:#6b7280,stroke-dasharray:4 3,color:#111827',
  action: 'fill:#f3f4f6,stroke:#9ca3af,color:#374151',
  start: 'fill:#f9fafb,stroke:#374151,color:#111827',
}

const LEGEND: { category: Category; meaning: string }[] = [
  { category: 'pref', meaning: 'User or workspace setting, feature flag, config' },
  { category: 'state', meaning: 'Runtime state read from a store or service' },
  { category: 'input', meaning: "The function's arguments or parsed request data" },
  { category: 'external', meaning: "A call Vantle couldn't look into" },
]

export function toMermaid(flow: AnyFlow): string {
  const short = new Map<string, string>()
  flow.nodes.forEach((n, i) => short.set(n.id, `n${i}`))
  const lines = ['flowchart TD', `  start(["${escape(flow.flow.question || flow.flow.id)}"]):::start`]

  const nodes: AnyNode[] = flow.nodes
  const byId = new Map(nodes.map((n) => [n.id, n]))
  for (const node of nodes) {
    lines.push(`  ${short.get(node.id)}${shape(node, flow.flow.returnsBoolean)}:::${className(node)}`)
  }
  lines.push(`  start --> ${short.get(flow.root)}`)

  // Switches can send several cases to the same place; draw those as one arrow.
  const merged = new Map<string, { from: string; to: string; labels: string[] }>()
  for (const e of flow.edges) {
    const key = `${e.from}->${e.to}`
    const entry = merged.get(key) ?? { from: e.from, to: e.to, labels: [] }
    entry.labels.push(edgeLabel(byId.get(e.from), e.label))
    merged.set(key, entry)
  }
  for (const e of merged.values()) {
    const label = e.labels.filter((l) => l !== 'next').join(', ')
    // Quoted, so labels can contain parentheses and other Mermaid syntax.
    const arrow = label ? `-->|"${escape(label)}"|` : '-->'
    lines.push(`  ${short.get(e.from)} ${arrow} ${short.get(e.to)}`)
  }

  for (const [name, style] of Object.entries(CLASS_DEFS)) lines.push(`  classDef ${name} ${style}`)
  return lines.join('\n') + '\n'
}

/**
 * A markdown page with the chart, legend and stats. By default it shows the SVG chart written
 * next to it, with the Mermaid version folded below. With `svg: false`, it shows only Mermaid.
 */
export function toMarkdown(flow: AnyFlow, { svg = true }: { svg?: boolean } = {}): string {
  const labeled = isLabeled(flow)
  const decisions = flow.nodes.filter((n) => n.kind === 'decision').length
  const outcomes = flow.nodes.filter((n) => n.kind === 'outcome').length
  const verified = flow.paths.filter((p) => p.status === 'verified').length
  const out: string[] = [
    `# ${flow.flow.question || flow.flow.id}`,
    '',
    `Generated by Vantle from \`${flow.flow.id}\` (line ${flow.flow.entry.line}) on ${flow.flow.generatedAt.slice(0, 10)}.`,
    labeled
      ? `Labels written by ${flow.labeling.model} and checked against the extracted chart. The table below shows the code behind each box.`
      : 'Boxes show the raw code for each condition. Product-language labels come from `vantle label`.',
    '',
    ...(svg
      ? [
          `![Chart of ${(flow.flow.question || flow.flow.id).replace(/[\\[\]]/g, '\\$&')}](./${flow.flow.slug}.svg)`,
          '',
          '<details><summary>The same chart in Mermaid</summary>',
          '',
          '```mermaid',
          toMermaid(flow).trimEnd(),
          '```',
          '',
          '</details>',
        ]
      : ['```mermaid', toMermaid(flow).trimEnd(), '```']),
    '',
    '## Legend',
    '',
    '| Color | Category | Data comes from |',
    '|---|---|---|',
    ...LEGEND.map((l) => `| ${swatch(l.category)} | \`${l.category}\` | ${l.meaning} |`),
    '',
    '## Stats',
    '',
    `- ${decisions} decisions, ${outcomes} outcomes`,
    `- ${flow.pathCount.toLocaleString('en-US')} paths${flow.pathsTruncated ? ` (first ${flow.paths.length} stored)` : ''}, ${verified} verified`,
  ]
  if (labeled) {
    const cost = flow.labeling.costUsd === null ? 'cost unknown' : `about $${flow.labeling.costUsd.toFixed(3)}`
    out.push(
      `- Labeling: ${flow.labeling.attempts} attempt${flow.labeling.attempts === 1 ? '' : 's'}, ${flow.labeling.inputTokens.toLocaleString('en-US')} input / ${flow.labeling.outputTokens.toLocaleString('en-US')} output tokens, ${cost}, ${(flow.labeling.durationMs / 1000).toFixed(1)} s`,
    )
  }
  if (flow.verification) {
    const v = flow.verification
    out.push(
      `- Verification: ${v.counts.verified} verified, ${v.counts.failed} failed, ${v.counts.untestable} couldn't build a test, ${v.counts.unverified} unverified; ${v.arrowsVerified} of ${v.arrowsTotal} arrows on a verified path (${v.verifiedAt.slice(0, 10)})`,
    )
    if (v.completeness) out.push(`- Code reached: ${completenessSummary(v.completeness)}`)
  }
  if (flow.notCharted?.length) {
    const cell = (text: string) => text.replace(/\|/g, '\\|').replace(/\n/g, ' ')
    out.push(
      '',
      '## Not charted',
      '',
      "This code affects what the function does, but the chart doesn't show it. Read it in the source.",
      '',
      '| Kind | Code | Where | Why |',
      '|---|---|---|---|',
      ...flow.notCharted.map((n) => `| ${NOT_CHARTED_WORDS[n.kind]} | \`${cell(n.code)}\` | \`${n.file}:${n.line}\` (${n.symbol}) | ${cell(n.note)} |`),
    )
  }
  if (flow.warnings.length) {
    out.push('', '## Warnings', '', ...flow.warnings.map((w) => `- ${w}`))
  }
  const cell = (text: string) => text.replace(/\|/g, '\\|')
  if (labeled) {
    out.push('', '## Where each box comes from', '', '| Box | Code | Category | Source |', '|---|---|---|---|')
    for (const n of flow.nodes) {
      if (n.kind !== 'decision') continue
      const category = n.category === n.categoryHint ? n.category : `${n.category} (guessed ${n.categoryHint})`
      out.push(`| ${cell(n.label)} | \`${cell(n.rawLabel)}\` | ${category} | \`${n.source.file}:${n.source.line}\` (${n.source.symbol}) |`)
    }
  } else {
    out.push('', '## Where each box comes from', '', '| Box | Category | Source |', '|---|---|---|')
    for (const n of flow.nodes) {
      if (n.kind !== 'decision') continue
      out.push(`| \`${cell(n.rawLabel)}\` | ${n.categoryHint} | \`${n.source.file}:${n.source.line}\` (${n.source.symbol}) |`)
    }
  }
  if (flow.verification) out.push('', ...pathsSection(flow))
  if (flow.verification?.completeness?.gaps.length) out.push('', ...gapsSection(flow.verification.completeness))
  return out.join('\n') + '\n'
}

const NOT_CHARTED_WORDS = { effect: 'effect', callback: 'callback', catch: 'catch block' }

/** "41 of 43 places in the code ran in a test …", for summaries. */
export function completenessSummary(c: Completeness): string {
  const ran = c.reachedByPaths + c.reachedOnChart
  const counts = (['missing', 'untested', 'untestable'] as const)
    .map((status) => [status, c.gaps.filter((g) => g.status === status).length] as const)
    .filter(([, n]) => n > 0)
    .map(([status, n]) => `${n} ${GAP_WORDS[status]}`)
  const extra = c.reachedOnChart ? ` (${c.reachedOnChart} by tests written to reach them)` : ''
  return `${ran} of ${c.places} returns, throws and branches ran in a test and stayed on the chart${extra}${counts.length ? `; ${counts.join(', ')}` : ''}`
}

const GAP_WORDS = { missing: 'missing from the chart', untested: 'not reached yet', untestable: "couldn't build a test" }
const GAP_MARK = { missing: '❌ missing from chart', untested: '❔ not reached', untestable: "⛔ couldn't build a test" }

/** Code no path test ran, and what a test written to reach it found. */
function gapsSection(c: Completeness): string[] {
  const cell = (text: string) => text.replace(/\|/g, '\\|').replace(/\n/g, ' ')
  const order = { missing: 0, untested: 1, untestable: 2 }
  const rows = [...c.gaps].sort((a, b) => order[a.status] - order[b.status] || a.file.localeCompare(b.file) || a.line - b.line)
  const out = [
    '## Code the chart may be missing',
    '',
    "No path test ran these. Vantle had a test written to reach each one, then checked whether the code stayed on the chart.",
    '',
    '| Place | Status | Code | Where | Notes |',
    '|---|---|---|---|---|',
  ]
  for (const g of rows) {
    const test = g.test ? ` ([test](${path.posix.relative('.vantle/flows', g.test)}))` : ''
    out.push(`| ${g.id}${test} | ${GAP_MARK[g.status]} | \`${cell(g.code)}\` | \`${g.file}:${g.line}\` (${g.symbol}) | ${cell((g.note ?? '').split('\n')[0] ?? '')} |`)
  }
  return out
}

const STATUS_MARK: Record<string, string> = { verified: '✅ verified', failed: '❌ failed', untestable: "⛔ couldn't build a test", unverified: '❔ unverified' }

/** One row per tested path: its answers in order, the outcome, and how its test ended. */
function pathsSection(flow: AnyFlow): string[] {
  const nodes: AnyNode[] = flow.nodes
  const byId = new Map(nodes.map((n) => [n.id, n]))
  const name = (id: string) => {
    const n = byId.get(id)
    if (!n) return id
    if ('label' in n) return n.label
    return n.kind === 'outcome' ? n.value : n.rawLabel
  }
  const cell = (text: string) => text.replace(/\|/g, '\\|').replace(/\n/g, ' ')
  const order = { failed: 0, unverified: 1, untestable: 2, verified: 3 }
  const rows = [...flow.paths].sort((a, b) => order[a.status] - order[b.status] || a.id.localeCompare(b.id))
  const out = ['## Paths tested', '', 'Each path has a test that drives the real code through these answers. Verified means the code took exactly this route and ended with this outcome: evidence for these inputs, not proof for every input.', '', '| Path | Status | Answers | Outcome | Notes |', '|---|---|---|---|---|']
  for (const p of rows) {
    const answers = p.steps.map((s) => `${name(s.node)} ${edgeLabel(byId.get(s.node), s.edge)}`).join(' → ')
    const test = p.test ? ` ([test](${path.posix.relative('.vantle/flows', p.test)}))` : ''
    out.push(`| ${p.id}${test} | ${STATUS_MARK[p.status] ?? p.status} | ${cell(answers)} | ${cell(name(p.outcome))} | ${cell((p.note ?? '').split('\n')[0] ?? '')} |`)
  }
  return out
}

function shape(node: AnyNode, returnsBoolean: boolean): string {
  const label = 'label' in node ? node.label : undefined
  if (node.kind === 'outcome') {
    const fallback = returnsBoolean && node.value === 'true' ? 'YES' : returnsBoolean && node.value === 'false' ? 'NO' : node.value
    return `(("${escape(label ?? fallback)}"))`
  }
  if (node.kind === 'opaque') return `[/"${escape(label ?? node.rawLabel)}"/]`
  if (node.kind === 'action') return `("${escape(label ?? node.rawLabel)}")`
  return `["${escape(label ?? `${node.rawLabel}?`)}"]`
}

function className(node: AnyNode): string {
  if (node.kind === 'outcome') return node.value === 'true' ? 'yes' : node.value === 'false' ? 'no' : 'outcome'
  if (node.kind === 'opaque') return 'opaque'
  if (node.kind === 'action') return 'action'
  return 'category' in node ? node.category : node.categoryHint
}

/** Switch cases show their label when one was written; yes/no stay as they are. */
export function edgeLabel(node: AnyNode | undefined, label: string): string {
  if (node?.kind === 'decision' && 'caseLabels' in node) return node.caseLabels[normalizeCode(label)] ?? label
  return label
}

const COLOR_NAMES: Record<Category, string> = { pref: 'Blue', state: 'Yellow', input: 'Orange', external: 'Gray' }

function swatch(category: Category): string {
  return COLOR_NAMES[category]
}

/** Mermaid labels are HTML; escape the characters that would break them. */
function escape(text: string): string {
  return text
    .replace(/&/g, '#amp;')
    .replace(/"/g, '#quot;')
    .replace(/</g, '#lt;')
    .replace(/>/g, '#gt;')
    .replace(/\|/g, '#124;')
    .replace(/\n/g, '<br/>')
}
